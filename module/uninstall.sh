#!/system/bin/sh
#
# uninstall.sh —— 完整还原（提示词 6.9 侵入原则 + 红线条 R6）。
#
# 这是整个模块**最关键**的脚本。
# 提示词 6.9 规定：「任何无法自动还原的操作，不允许实现」。
# 因此本脚本必须能清理模块做过的一切。
#
# 还原顺序有讲究（从依赖链的末端往根部拆）：
#   1. 先停掉所有挂载（否则删除挂载源会留下悬空的挂载点）
#   2. 再移除证书注入
#   3. 最后删除数据目录
#
# M1 状态：逻辑完整实现，但因为 M1 没有任何实际挂载，
#         执行时只会清理空的目录结构 —— 这是正确的行为。

SYFUSE_DATA="/data/adb/syfuse"

echo "- Syfuse 卸载：开始完整还原"

# ---------------------------------------------------------------------------
# 步骤 1：卸载所有挂载点
# ---------------------------------------------------------------------------
# 遍历 manifest 中登记的每一项，逐一卸载。
# 之所以要按 manifest 而不是硬编码路径清单：
# 若用户只启用了部分功能（例如只注入了 hosts 但没装 CA），
# 硬编码清单会产生大量「未挂载」的报错噪音，
# 而 manifest 精确反映实际做了什么。
if [ -f "${SYFUSE_DATA}/manifest/installed.json" ]; then
    echo "  读取改动清单…"

    # 提取所有 target 字段（bind mount 的目标路径）
    # 用 grep + sed 而非 jq：模块环境不保证有 jq
    TARGETS=$(grep -o '"target":"[^"]*"' "${SYFUSE_DATA}/manifest/installed.json" \
        | sed 's/"target":"//; s/"$//')

    for target in ${TARGETS}; do
        if [ -n "${target}" ]; then
            echo "  卸载挂载：${target}"
            umount "${target}" 2>/dev/null || \
                umount -l "${target}" 2>/dev/null || \
                echo "    警告：卸载失败，可能需要重启完成清理"
        fi
    done

    echo "  挂载点处理完毕"
else
    echo "  无改动清单，跳过挂载卸载"
fi

# ---------------------------------------------------------------------------
# 步骤 2：移除系统证书注入
# ---------------------------------------------------------------------------
# 提示词 6.5 要求系统 CA 以「独立子模块」形式安装，以便单独卸载。
# 这里检查并移除残留（证书由 App 侧在 root 模式下写入）。
CACERT_MARKER="${SYFUSE_DATA}/ca-injected"

if [ -f "${CACERT_MARKER}" ]; then
    echo "  检测到证书注入记录，移除注入的 CA…"

    # 证书以 subject_hash 命名，具体文件名记录在 marker 文件中
    while IFS= read -r cert_file; do
        if [ -n "${cert_file}" ] && [ -f "${cert_file}" ]; then
            echo "    删除：${cert_file}"
            rm -f "${cert_file}"
        fi
    done < "${CACERT_MARKER}"

    echo "  证书清理完毕（重启后系统信任列表恢复）"
else
    echo "  未检测到证书注入，跳过"
fi

# ---------------------------------------------------------------------------
# 步骤 3：清理 hosts 注入残留
# ---------------------------------------------------------------------------
# 使用 bind mount 方案时，原 hosts 文件从未被修改，
# 卸载挂载点即自动恢复 —— 这正是选择 bind mount 而非直接改写的原因。
HOSTS_BAK="${SYFUSE_DATA}/hosts.orig"

if [ -f "${HOSTS_BAK}" ]; then
    echo "  检测到 hosts 备份"
    echo "  说明：hosts 通过 bind mount 注入，原文件未被修改，"
    echo "        卸载挂载点即已完全恢复。备份文件随之删除。"
fi

# ---------------------------------------------------------------------------
# 步骤 4：删除数据目录
# ---------------------------------------------------------------------------
echo "  删除数据目录：${SYFUSE_DATA}"
rm -rf "${SYFUSE_DATA}"

echo "- Syfuse 卸载完成"
echo "- 所有改动已还原。建议重启设备以应用最终状态。"
