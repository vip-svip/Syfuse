#!/usr/bin/env bash
#
# 端到端测试（提示词第 12 部分）。
#
# 定位：「真起隧道、真发请求、逐条断言」。
#
# 当前状态（M1）：**未实现，脚本会以明确的非零退出码失败**。
# 这是有意设计，不是遗漏 ——
# 提示词 2.3 第 8 条禁止「无法自测的代码」，同时第 6 条禁止「沉默失败」。
# 一个在 M1 就返回成功的 e2e 脚本是虚假证据；返回明确失败才是诚实的。
#
# M2 起填充：起 TUN → 发请求 → 断言走代理 → 校验 DNS 泄漏。

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${PROJECT_ROOT}"

cat >&2 <<'EOF'
==> 端到端测试：尚未实现

原因：E2E 需要真实内核与隧道，而 M1 尚未接入 sing-box 二进制（计划于 M2）。
      当前不存在可端到端验证的链路，因此本脚本不产生任何「通过」结论。

M2 的填充计划：
  1. 构建 sing-box AAR，启动 TUN
  2. 通过隧道发起 HTTP 请求，断言出口 IP 与预期一致
  3. 断言 DNS 查询确实走隧道（防泄漏）
  4. 断言规则命中的连接出现在连接列表中

在此之前，本脚本以退出码 78（EX_CONFIG，未配置完成）失败，
以便 CI 明确区分「未实现」与「实现但有缺陷」。
EOF

exit 78
